-- DESKRIPSI: Struktur tabel SAPA DINSOS versi Supabase (PostgreSQL).
-- Pengganti migration Laravel:
--   users + profiles  -> auth.users (bawaan Supabase) + public.profiles
--   layanans          -> public.layanans
--   antreans          -> public.antreans
-- Catatan: di file SQL, komentar ditulis dengan "--" (setara "//" di JavaScript).
-- Cara pakai: jalankan PERTAMA di Supabase > SQL Editor.
-- ======================================================================

-- pgcrypto dipakai untuk membuat kode acak & memeriksa kata sandi (bcrypt).
-- Di Supabase, ekstensi ini sudah tersedia di skema "extensions".
create extension if not exists pgcrypto with schema extensions;

-- ----------------------------------------------------------------------
-- 1. TABEL PROFILES (pengganti tabel profiles + kolom is_active di users)
-- Satu baris untuk setiap akun login (auth.users). Berisi nama, HP, role.
-- ----------------------------------------------------------------------
create table if not exists public.profiles (
  -- Sama dengan id akun di auth.users. Jika akun dihapus, profil ikut terhapus.
  id         uuid primary key references auth.users (id) on delete cascade,
  -- Nama lengkap
  nama       text not null,
  -- Alamat (boleh kosong)
  alamat     text,
  -- Nomor HP format 08xxxxxxxxxx (dipakai untuk login dengan nomor HP)
  no_telp    text,
  -- Role: hanya 3 nilai ini (sama dengan enum di migration Laravel)
  role       text not null default 'pengunjung'
             check (role in ('pengunjung', 'petugas_pendaftaran', 'petugas_pelayanan')),
  -- true = akun aktif, false = dinonaktifkan administrator (tidak bisa login)
  is_active  boolean not null default true,
  -- Jejak waktu
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Nomor HP tidak boleh dipakai dua akun (sama dengan 'unique:profiles,no_telp' di Laravel)
create unique index if not exists profiles_no_telp_unik
  on public.profiles (no_telp) where no_telp is not null;

-- ----------------------------------------------------------------------
-- 2. TABEL LAYANANS (jenis layanan Dinas Sosial)
-- ----------------------------------------------------------------------
create table if not exists public.layanans (
  -- Nomor urut otomatis (sama seperti id auto-increment Laravel)
  id           bigint generated by default as identity primary key,
  -- Nama layanan, unik agar data awal tidak dobel saat dijalankan ulang
  nama_layanan text not null unique,
  deskripsi    text,
  -- Persyaratan, satu baris = satu syarat
  persyaratan  text,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

-- ----------------------------------------------------------------------
-- 3. TABEL ANTREANS (inti sistem antrean, sesuai flowchart)
-- ----------------------------------------------------------------------
create table if not exists public.antreans (
  id                   bigint generated by default as identity primary key,

  -- --- DATA PEMILIK ANTREAN ---
  -- Akun pengunjung. NULL jika warga daftar langsung di loket.
  user_id              uuid references auth.users (id) on delete set null,
  -- Data buku tamu digital
  nama_pengunjung      text,
  no_telp_pengunjung   text,
  desa_kelurahan       text,
  kecamatan            text,
  keperluan            text,

  -- --- JENIS LAYANAN & CARA DAFTAR ---
  layanan_id           bigint not null references public.layanans (id) on delete cascade,
  jenis_pendaftaran    text not null default 'online'
                       check (jenis_pendaftaran in ('online', 'langsung')),

  -- --- KODE ANTREAN & BARCODE ---
  -- Contoh: A001 (urut per hari)
  nomor_antrean        text not null,
  -- Isi barcode/QR, contoh: DNS-K3J9... (acak, tidak bisa ditebak)
  kode_barcode         text unique,

  -- --- STATUS (mengikuti flowchart) ---
  status               text not null default 'menunggu'
                       check (status in ('menunggu', 'terverifikasi', 'dipanggil', 'dilayani', 'selesai', 'dibatalkan')),
  -- Tanggal antrean (zona waktu WIB). Nomor urut direset setiap hari.
  tanggal              date not null,

  -- --- JEJAK PETUGAS ---
  didaftarkan_oleh     uuid references auth.users (id) on delete set null,
  diverifikasi_oleh    uuid references auth.users (id) on delete set null,
  dilayani_oleh        uuid references auth.users (id) on delete set null,
  dibatalkan_oleh      uuid references auth.users (id) on delete set null,

  -- --- JEJAK WAKTU ---
  waktu_verifikasi     timestamptz,
  waktu_dipanggil      timestamptz,
  waktu_mulai_dilayani timestamptz,
  waktu_selesai        timestamptz,
  waktu_dibatalkan     timestamptz,
  alasan_batal         text,

  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now(),

  -- Mencegah nomor antrean ganda pada hari yang sama
  constraint antreans_nomor_unik_per_hari unique (tanggal, nomor_antrean)
);

-- Mempercepat pencarian antrean per hari berdasarkan status
create index if not exists antreans_tanggal_status on public.antreans (tanggal, status);
-- Mempercepat "antrean saya" untuk pengunjung
create index if not exists antreans_user on public.antreans (user_id);

-- PENGAMAN DI DATABASE: satu petugas pelayanan hanya boleh memegang SATU antrean
-- (dipanggil/dilayani) per hari. Walau 2 klik datang bersamaan, database menolak yang kedua.
create unique index if not exists antreans_satu_petugas_satu_antrean
  on public.antreans (dilayani_oleh, tanggal)
  where status in ('dipanggil', 'dilayani');

-- ----------------------------------------------------------------------
-- 4. TABEL CATATAN LOGIN GAGAL (pengganti RateLimiter Laravel untuk login nomor HP)
-- ----------------------------------------------------------------------
create table if not exists public.login_gagal (
  id    bigint generated by default as identity primary key,
  -- Nomor HP yang dicoba
  kunci text not null,
  -- Waktu percobaan gagal
  waktu timestamptz not null default now()
);
create index if not exists login_gagal_kunci on public.login_gagal (kunci, waktu);

-- ----------------------------------------------------------------------
-- 5. TRIGGER updated_at OTOMATIS (pengganti timestamps() Laravel)
-- ----------------------------------------------------------------------
create or replace function public._set_updated_at()
returns trigger
language plpgsql
as $$
begin
  -- Setiap kali baris diubah, isi updated_at dengan waktu sekarang
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists profiles_updated_at on public.profiles;
create trigger profiles_updated_at before update on public.profiles
  for each row execute function public._set_updated_at();

drop trigger if exists layanans_updated_at on public.layanans;
create trigger layanans_updated_at before update on public.layanans
  for each row execute function public._set_updated_at();

drop trigger if exists antreans_updated_at on public.antreans;
create trigger antreans_updated_at before update on public.antreans
  for each row execute function public._set_updated_at();
